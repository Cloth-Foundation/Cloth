package cloth.development

import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.util.*
import java.util.zip.GZIPOutputStream

/** Offline, reproducible extraction from authenticated upstream Unicode 17 files.
 * Run :Compiler:generateUnicodeCharacterTables --args=<input-directory>.
 */
fun main(args: Array<String>) {
	check(args.size == 1) { "Supply the directory containing the five pinned Unicode input files" }
	val inputs = Path.of(args.single())
	val hashes = linkedMapOf(
		"DerivedGeneralCategory.txt" to "d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e",
		"DerivedCoreProperties.txt" to "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
		"PropList.txt" to "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
		"UnicodeData.txt" to "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
		"LICENSE.txt" to "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96",
	)
	val files = hashes.mapValues { (name, expected) ->
		Files.readAllBytes(inputs.resolve(name)).also { bytes ->
			check(HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)) == expected) { "Unexpected Unicode input hash: $name" }
		}
	}
	val properties = linkedMapOf("LETTER" to mutableListOf<IntRange>(), "DIGIT" to mutableListOf(), "UPPERCASE" to mutableListOf(), "LOWERCASE" to mutableListOf())
	val row = Regex("^([0-9A-F]+)(?:\\.\\.([0-9A-F]+))?\\s*;\\s*(\\w+)\\b")
	for (name in listOf("DerivedGeneralCategory.txt", "DerivedCoreProperties.txt")) {
		val text = files.getValue(name).toString(Charsets.UTF_8)
		check(text.lineSequence().first().contains("17.0.0"))
		for (line in text.lineSequence()) {
			val match = row.find(line) ?: continue
			val property = when (val value = match.groupValues[3]) {
				"Lu", "Ll", "Lt", "Lm", "Lo" -> if (name == "DerivedGeneralCategory.txt") "LETTER" else continue
				"Nd"                         -> if (name == "DerivedGeneralCategory.txt") "DIGIT" else continue
				"Uppercase", "Lowercase"     -> if (name == "DerivedCoreProperties.txt") value.uppercase(java.util.Locale.ROOT) else continue
				else                         -> continue
			}
			val first = match.groupValues[1].toInt(16)
			val last = match.groupValues[2].ifEmpty { match.groupValues[1] }.toInt(16)
			properties.getValue(property).add(first..last)
		}
	}
	val merged = properties.mapValues { (_, ranges) ->
		val result = mutableListOf<IntRange>()
		for (range in ranges.sortedBy { it.first }) {
			if (result.isNotEmpty() && range.first <= result.last().last + 1) result[result.lastIndex] = result.last().first..maxOf(range.last, result.last().last)
			else result.add(range)
		}
		check(result.isNotEmpty())
		result
	}
	val mappings = linkedMapOf("UPPER" to sortedMapOf<Int, Int>(), "LOWER" to sortedMapOf())
	for (line in files.getValue("UnicodeData.txt").toString(Charsets.UTF_8).lineSequence().filter { it.isNotBlank() }) {
		val fields = line.split(';')
		check(fields.size == 15) { "Malformed UnicodeData row" }
		val scalar = fields[0].toInt(16)
		for ((kind, index) in listOf("UPPER" to 12, "LOWER" to 13)) if (fields[index].isNotEmpty()) {
			val mapped = fields[index].toInt(16)
			check(scalar in 0..0x10ffff && scalar !in 0xd800..0xdfff && mapped in 0..0x10ffff && mapped !in 0xd800..0xdfff)
			if (mapped != scalar) check(mappings.getValue(kind).put(scalar, mapped) == null) { "Duplicate simple case mapping" }
		}
	}
	check(mappings.values.all { it.isNotEmpty() })
	val output = Path.of("Compiler/src/main/resources/cloth/unicode/17.0.0")
	val oracle = Path.of("Compiler/src/test/resources/cloth/unicode/17.0.0")
	Files.createDirectories(output)
	Files.createDirectories(oracle)
	val table = buildString {
		appendLine("# Unicode 17.0.0 character properties")
		appendLine("# Copyright © 2025 Unicode, Inc.; SPDX-License-Identifier: Unicode-3.0")
		appendLine("# License: LICENSE.txt. Generated by GenerateUnicodeCharacterTables; do not edit.")
		appendLine("# Sources: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedGeneralCategory.txt")
		appendLine("#          https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt")
		for ((name, hash) in hashes.filterKeys { it != "UnicodeData.txt" }) appendLine("# SHA256 $name $hash")
		for ((property, ranges) in merged) for (range in ranges) appendLine("$property;${range.first.toString(16)};${range.last.toString(16)}")
	}
	Files.writeString(output.resolve("character-ranges.txt"), table)
	val casing = buildString {
		appendLine("# Unicode 17.0.0 simple character case mappings")
		appendLine("# Copyright © 2025 Unicode, Inc.; SPDX-License-Identifier: Unicode-3.0")
		appendLine("# License: LICENSE.txt. Generated by GenerateUnicodeCharacterTables; do not edit.")
		appendLine("# Source: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt")
		appendLine("# SHA256 UnicodeData.txt ${hashes.getValue("UnicodeData.txt")}")
		for ((kind, entries) in mappings) for ((scalar, mapped) in entries) appendLine("$kind;${scalar.toString(16)};${mapped.toString(16)}")
	}
	Files.writeString(output.resolve("character-case-mappings.txt"), casing)
	Files.write(output.resolve("LICENSE.txt"), files.getValue("LICENSE.txt"))
	for (name in hashes.keys.filter { it != "LICENSE.txt" }) GZIPOutputStream(Files.newOutputStream(oracle.resolve("$name.gz"))).use { it.write(files.getValue(name)) }
	println(merged.mapValues { (_, ranges) -> "${ranges.size} ranges, ${ranges.sumOf { it.last - it.first + 1 }} scalars" })
	println(mappings.mapValues { (_, entries) -> "${entries.size} simple mappings" })
}
